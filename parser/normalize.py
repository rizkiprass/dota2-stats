"""
Normalizes the line-delimited JSON event stream produced by odota/parser
(https://github.com/odota/parser) into the minimal MVP match schema
described in dota_replay_mvp_plan.md (Section 6/7):

{
  "match_id": "...",
  "duration": 2518,
  "radiant_win": true,
  "start_time": 1234567890,
  "game_mode": 22,
  "lobby_type": 1,
  "players": [
    {
      "account_id": "...",
      "steam_id": "...",
      "player_name": "...",
      "hero_id": 2,
      "team": "radiant",
      "kills": 12,
      "deaths": 4,
      "assists": 18,
      "win": true
    },
    ...
  ]
}

odota/parser's event stream is generated by Java's Gson serializing internal
protobuf-generated objects directly (see opendota/Parse.java, the "epilogue"
event). That means field names in the embedded protobuf JSON can vary
depending on the protobuf/Gson version in use (e.g. "matchId_" vs "matchId").
To stay robust against this, `_find` below searches recursively for a field
by a set of case-insensitive candidate names, ignoring any trailing
underscore Gson/protobuf commonly adds to generated field names.
"""

from __future__ import annotations

import json
import re
from typing import Any, Iterable, Optional

STEAM64_BASE = 76561197960265728
PING_BURST_WINDOW_SECONDS = 5
PING_BURST_MINIMUM = 3

# Prefix used by Source 2 hero entity class names, e.g. "CDOTA_Unit_Hero_Zuus"
_HERO_UNIT_PREFIX = "CDOTA_Unit_Hero_"


def _normalize_key(key: str) -> str:
    """Normalize a Gson-serialized protobuf field name for matching.

    Protobuf-generated Java fields are typically camelCase with a trailing
    underscore (e.g. "matchId_", "playbackTime_", "steamid_"). Stripping all
    underscores and lowercasing makes "matchId_", "match_id" and "matchid"
    all compare equal.
    """
    return key.replace("_", "").lower()


def _find(obj: Any, *candidates: str) -> Any:
    """Recursively search a nested dict/list for the first value whose key
    matches (case-insensitively, ignoring a trailing underscore) any of the
    given candidate names."""
    wanted = {_normalize_key(c) for c in candidates}
    stack = [obj]
    while stack:
        current = stack.pop()
        if isinstance(current, dict):
            for k, v in current.items():
                if _normalize_key(k) in wanted:
                    return v
            stack.extend(current.values())
        elif isinstance(current, list):
            stack.extend(current)
    return None


def _find_all_dicts(obj: Any, *candidates: str) -> list:
    """Recursively find every list-of-dicts value stored under a key
    matching any of the candidate names. Used to locate the repeated
    player_info entries regardless of exact field naming."""
    wanted = {_normalize_key(c) for c in candidates}
    results = []
    stack = [obj]
    while stack:
        current = stack.pop()
        if isinstance(current, dict):
            for k, v in current.items():
                if _normalize_key(k) in wanted and isinstance(v, list):
                    results.append(v)
            stack.extend(current.values())
        elif isinstance(current, list):
            stack.extend(current)
    return results


def _hero_combat_log_names(unit: str) -> list:
    """Given a hero entity class name like 'CDOTA_Unit_Hero_Zuus', build the
    candidate combat-log-style names odota/parser itself derives
    (see Parse.java), so we can match against CPlayerInfo.hero_name."""
    if not unit or not unit.startswith(_HERO_UNIT_PREFIX):
        return []
    ending = unit[len(_HERO_UNIT_PREFIX):]
    name1 = "npc_dota_hero_" + ending.lower()
    name2 = "npc_dota_hero" + re.sub(r"([A-Z])", r"_\1", ending).lower()
    return [name1, name2]


def _decode_protobuf_string(value: Any) -> Optional[str]:
    """Decode a Java protobuf ByteString serialized by Gson.

    Recent odota/parser builds serialize `ByteString` fields as
    ``{"bytes": [110, 112, ..., -40], "hash": 0}``, rather than JSON
    strings. Java bytes are signed, therefore negative values must be mapped
    back to their unsigned 0-255 representation before UTF-8 decoding.
    """
    if isinstance(value, str):
        return value
    if not isinstance(value, dict) or not isinstance(value.get("bytes"), list):
        return None
    try:
        return bytes(byte & 0xFF for byte in value["bytes"]).decode("utf-8")
    except (TypeError, ValueError, UnicodeDecodeError):
        return None


def _steam64_to_account_id(steam_id: Optional[int]) -> Optional[int]:
    if steam_id is None:
        return None
    account_id = int(steam_id) - STEAM64_BASE
    return account_id if account_id >= 0 else None


def _parse_lines(raw_output: str) -> list:
    events = []
    for line in raw_output.splitlines():
        line = line.strip()
        if not line:
            continue
        try:
            events.append(json.loads(line))
        except json.JSONDecodeError:
            # Skip any non-JSON noise (shouldn't normally happen, but avoid
            # failing the whole parse over a single malformed line).
            continue
    return events


def _finalize_behavior(raw: Optional[dict[str, Any]]) -> dict[str, Any]:
    """Convert one slot's raw replay activity into persisted count-only data."""
    raw = raw or {}
    pings = sorted(raw.get("pings", []))
    ping_bursts = 0
    burst_start = None
    burst_count = 0
    for timestamp in pings:
        if burst_start is None or timestamp - burst_start > PING_BURST_WINDOW_SECONDS:
            if burst_count >= PING_BURST_MINIMUM:
                ping_bursts += 1
            burst_start = timestamp
            burst_count = 1
        else:
            burst_count += 1
    if burst_count >= PING_BURST_MINIMUM:
        ping_bursts += 1
    return {
        "chat_messages": raw.get("chat_messages", 0),
        "pings": len(pings),
        "ping_bursts": ping_bursts,
        "chatwheel": raw.get("chatwheel", {}),
        "disconnects": raw.get("disconnects", 0),
        "abandons": raw.get("abandons", 0),
    }


def normalize_events(raw_output: str, match_id_hint: str) -> dict:
    """Convert the raw odota/parser stdout into the MVP match JSON schema.

    match_id_hint is the match id derived from the uploaded file name
    (raw/<match_id>.dem) and is used as a fallback if the parser output
    doesn't expose match_id explicitly.
    """
    events = _parse_lines(raw_output)

    epilogue = None
    match_info = None
    player_slot_by_index: dict = {}  # slot index (0-9) -> player_slot value (0-127 radiant / 128-255 dire)
    latest_interval_by_slot: dict = {}  # slot index -> latest interval event
    behavior_by_slot: dict[int, dict[str, Any]] = {}

    def behavior_for(slot: Any) -> Optional[dict[str, Any]]:
        try:
            normalized_slot = int(slot)
        except (TypeError, ValueError):
            return None
        return behavior_by_slot.setdefault(
            normalized_slot,
            {"chat_messages": 0, "pings": [], "chatwheel": {}, "disconnects": 0, "abandons": 0},
        )

    for e in events:
        etype = e.get("type")
        if etype == "epilogue":
            key = e.get("key")
            if isinstance(key, str):
                try:
                    epilogue = json.loads(key)
                except json.JSONDecodeError:
                    epilogue = None
            elif isinstance(key, dict):
                epilogue = key
        elif etype == "match_info":
            key = e.get("key")
            if isinstance(key, str):
                try:
                    match_info = json.loads(key)
                except json.JSONDecodeError:
                    match_info = None
            elif isinstance(key, dict):
                match_info = key
        elif etype == "player_slot":
            try:
                idx = int(e.get("key"))
                player_slot_by_index[idx] = e.get("value")
            except (TypeError, ValueError):
                pass
        elif etype == "interval":
            slot = e.get("slot")
            if slot is None:
                continue
            time_ = e.get("time") or 0
            prev = latest_interval_by_slot.get(slot)
            if prev is None or (prev.get("time") or 0) <= time_:
                latest_interval_by_slot[slot] = e
        elif etype in {"chat", "chatwheel", "pings"}:
            behavior = behavior_for(e.get("slot"))
            if behavior is None:
                continue
            if etype == "chat":
                behavior["chat_messages"] += 1
            elif etype == "chatwheel":
                key = str(e.get("key", "unknown"))
                behavior["chatwheel"][key] = behavior["chatwheel"].get(key, 0) + 1
            else:
                time_ = e.get("time")
                if isinstance(time_, (int, float)):
                    behavior["pings"].append(float(time_))
        elif isinstance(etype, str):
            behavior = behavior_for(e.get("player1"))
            if behavior is None:
                continue
            if etype.startswith("CHAT_MESSAGE_DISCONNECT"):
                behavior["disconnects"] += 1
            elif etype.startswith("CHAT_MESSAGE_PLAYER_ABANDONED"):
                behavior["abandons"] += 1

    dota_info = epilogue if epilogue is not None else {}

    match_id = _find(dota_info, "matchId", "match_id") or match_id_hint
    game_mode = _find(dota_info, "gameMode", "game_mode")
    # lobby_type comes from the patched CMsgDOTAMatch ``match_info`` event and
    # is the authoritative private-lobby vs public-matchmaking signal (1 =
    # Practice/private lobby, 0 = Normal/public, 7 = Ranked). game_mode is NOT
    # a discriminator: public and private Turbo matches both use game_mode 23.
    lobby_type = _find(match_info or {}, "lobbyType", "lobby_type")
    game_winner = _find(dota_info, "gameWinner", "game_winner")
    playback_time = _find(dota_info, "playbackTime", "playback_time")
    end_time = _find(dota_info, "endTime", "end_time")

    radiant_win = None
    if game_winner is not None:
        # 2 = radiant, 3 = dire (see opendota/Parse.java draftStage/team constants
        # and the commented reference decoder in CreateParsedDataBlob.java)
        radiant_win = int(game_winner) == 2

    duration = int(round(playback_time)) if isinstance(playback_time, (int, float)) else None
    start_time = int(end_time) - duration if isinstance(end_time, (int, float)) and duration is not None else None

    # player_info entries (CGameInfo.CDotaGameInfo.CPlayerInfo), matched to
    # slots via derived hero combat-log name. This mirrors the matching
    # odota/parser performs internally (name_to_slot) but reconstructed here
    # from the exposed event stream only.
    player_info_lists = _find_all_dicts(dota_info, "playerInfo", "player_info")
    player_infos = player_info_lists[0] if player_info_lists else []

    hero_name_to_info = {}
    for pi in player_infos:
        hero_name = _decode_protobuf_string(_find(pi, "heroName", "hero_name"))
        if hero_name:
            hero_name_to_info[hero_name.lower()] = pi

    players = []
    for slot in sorted(latest_interval_by_slot.keys()):
        interval = latest_interval_by_slot[slot]
        player_slot_value = player_slot_by_index.get(slot)
        team = None
        if player_slot_value is not None:
            team = "radiant" if player_slot_value < 128 else "dire"

        unit = interval.get("unit")
        info = None
        for candidate_name in _hero_combat_log_names(unit or ""):
            info = hero_name_to_info.get(candidate_name.lower())
            if info:
                break

        steam_id = _find(info, "steamid", "steam_id") if info else None
        player_name = _decode_protobuf_string(_find(info, "playerName", "player_name")) if info else None
        account_id = _steam64_to_account_id(steam_id)

        win = None
        if team is not None and radiant_win is not None:
            win = (team == "radiant") == radiant_win

        players.append(
            {
                "account_id": str(account_id) if account_id is not None else None,
                "steam_id": str(steam_id) if steam_id is not None else None,
                "player_name": player_name,
                "hero_id": interval.get("hero_id"),
                "team": team,
                "kills": interval.get("kills"),
                "deaths": interval.get("deaths"),
                "assists": interval.get("assists"),
                "win": win,
                # Keep counts only. The raw chat message in the event's key is
                # intentionally discarded before this parsed match is persisted.
                "behavior": _finalize_behavior(behavior_for(slot)),
            }
        )

    return {
        "match_id": str(match_id) if match_id is not None else match_id_hint,
        "duration": duration,
        "radiant_win": radiant_win,
        "start_time": start_time,
        "game_mode": game_mode,
        "lobby_type": lobby_type,
        "players": players,
    }
